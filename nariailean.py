#!/usr/bin/env python3
"""nariailean.py -- the Appendix B claims that a kernel can settle.

Appendix B is mostly analysis: Fourier transforms, improper integrals,
covariance matrices over the reals.  None of that is going into a
Mathlib-free Lean file.  But three of its load-bearing steps are not
analysis at all -- they are finite algebra wearing an analyst's clothes --
and those are worth proving rather than asserting, for the same reason the
Spectre repo proves its recurrences: a numerical check at three parameter
points is evidence, and an induction is not.

What is proved here
-------------------
1. THE MODULAR WEIGHT, as exponent bookkeeping.  The README states the
   identity as `(-U) dU = du / kappa`.  Taken literally that is FALSE: with
   U = -e^{-ku}/k one has (-U)(dU/du) = e^{-2ku}/k, not 1/k.  The true
   statement needs the derivative factors that accompany it in the integrand,
   since d_U = e^{ku} d_u contributes e^{+2ku} to a squared first derivative.
   Stripped to exponents of e^{ku} the three factors are -1, +2, -1, and the
   content of the identity is that they sum to zero.  Both the balance and
   the failure of the naive form are decidable.

2. THE MECHANISM OF I2 = 0, as a statement about a sumset.  I2 is the
   zero-frequency Fourier component of (d_u chi)^2, and (d_u chi)^2 has
   spectrum the sumset of the spectrum of d_u chi.  So I2 vanishes exactly
   when 0 is not a sum of two frequencies in the packet.  For a
   boost-positive-frequency packet every frequency is positive and no two
   sum to zero; for real (boost-blind) data the spectrum is symmetric and
   w + (-w) = 0 is attained.  That dichotomy is the whole theorem, it is
   combinatorial, and it is proved below for arbitrary finite spectra.

3. THE ONE-MODE SUM RULE, as ring identities.  The squeeze is
   S = diag(s, t) with st = 1 acting on sigma = nu * I.  Two polynomial
   identities carry the physics: the determinant is unchanged, so the
   symplectic eigenvalue and hence the von Neumann entropy are unchanged;
   and the trace gap factors as a perfect square, which is both the closed
   form (s - t)^2 = 4 sinh^2 r and the reason the energy cost is never
   negative.  Both are stated unconditionally as identities in three free
   variables, with st = 1 applied afterwards, so nothing is hidden in a
   hypothesis that only holds at the physical point.

What is NOT proved here
-----------------------
That any of this is a statement about the continuum.  The Lean layer proves
the algebra; the analysis stays in the paper.

Two items that used to be on this list have moved off it, and section 5
below is the reason for the first.  The packet of
appendix_b_verification.py is a truncated Gaussian and does NOT have
strictly positive spectrum, so the theorems of section 2 did not apply to
it; nariai_exact.py builds one that does, on an integer frequency grid, and
section 5 instantiates the theorem at that exact index list.  And the claim
that the covariance formalism computes the Araki relative entropy is now
checked against the definition in a truncated Fock space rather than
asserted.  Neither is a Lean proof -- the second is numerics -- but neither
is an admission any more either.

    python3 nariailean.py            # write NariaiFacts.lean
    python3 nariailean.py --stdout
    python3 nariailean.py --check    # prove it and audit the axioms
"""

